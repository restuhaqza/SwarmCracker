const emitSpec = `    Documents:
      type: array
      items: {$ref: '#/components/schemas/Service'}
    Patch:
      type: object
      properties:
        spec:
          anyOf:
            - {$ref: '#/components/schemas/Service'}
            - {type: 'null'}
        extra:
          type: object
          additionalProperties: true
    SecretWrite:
      type: object
      required: [name]
      oneOf:
        - required: [data]
        - required: [driver]
      properties:
        name: {type: string}
        data: {type: string, format: byte}
        driver: {type: string}
    Service:
      type: object
      description: >
        A service.
      required: [id, name]
      properties:
        id: {type: string}
        name: {type: string}
        labels:
          type: object
          additionalProperties: {type: string}
        mode: {type: string, enum: [replicated, global]}
        updatedAt: {type: string, format: date-time}
    ServiceMode:
      type: string
      enum: [replicated, global]
`

