// Command sdkgen generates the Python and TypeScript models of the SwarmCracker
// API v1 from api/openapi.yaml.
//
// The generator reads only components.schemas and resolves it into a small
// intermediate representation (the Type tree below). Each emitter turns that
// representation into one committed file, so the models cannot drift from the
// normative spec without `make sdk-check` failing. Anything the generator does
// not understand is a hard error carrying the document path, never a silently
// dropped field.
//
// Output is deterministic: schemas are alphabetical, properties keep their spec
// order and nothing iterates a Go map.
package main

import (
	"fmt"
	"sort"
	"strings"
	"unicode"

	"gopkg.in/yaml.v3"
)

// generatedHeader is the first line of every generated file (behind the
// language's comment marker).
const generatedHeader = "Code generated by tools/sdkgen from api/openapi.yaml. DO NOT EDIT."

// Kind is the resolved shape of a schema node.
type Kind int

// The supported schema shapes. Everything else is a parse error.
const (
	// KindObject is an object with named properties and/or additionalProperties.
	KindObject Kind = iota
	// KindArray is an array with a single items schema.
	KindArray
	// KindString is a string scalar.
	KindString
	// KindInteger is an integer scalar.
	KindInteger
	// KindNumber is a floating-point scalar.
	KindNumber
	// KindBoolean is a boolean scalar.
	KindBoolean
	// KindNull is the JSON null type (only meaningful in a union).
	KindNull
	// KindRef is a reference to another component schema.
	KindRef
	// KindUnion is a oneOf/anyOf union.
	KindUnion
	// KindEnum is a scalar constrained to a set of literals.
	KindEnum
)

// Literal is one enum value, kept as the spec wrote it so both emitters render
// the same token.
type Literal struct {
	// Raw is the scalar text, without quotes.
	Raw string
	// IsString reports whether the value was a string.
	IsString bool
	// IsBool reports whether the value was a boolean.
	IsBool bool
}

// Property is one named member of an object, in spec order.
type Property struct {
	Name string
	Type *Type
}

// Type is the resolved schema of one node. It is a tree: a $ref stays a name so
// the emitters can emit a named reference instead of inlining the target.
type Type struct {
	Kind        Kind
	Nullable    bool
	Description string
	// Format is the OpenAPI format, if any. Only byte and date-time change the
	// emitted type name; other formats are validated away.
	Format string

	// Ref is the target component schema name for KindRef.
	Ref string
	// Items is the element schema for KindArray.
	Items *Type
	// Variants holds the members of KindUnion.
	Variants []*Type
	// Properties is the ordered member list of KindObject.
	Properties []Property
	// Required is the ordered required set of KindObject.
	Required []string
	// HasExtra reports whether additionalProperties was declared and is not
	// false. Extra is nil for a free-form map.
	HasExtra bool
	Extra    *Type
	// Enum holds the literals of KindEnum.
	Enum []Literal
	// Merged reports that this object is the result of an allOf merge. An inline
	// occurrence of such an object is given a synthesised component name so it
	// can carry its merged required set (Partial.error).
	Merged bool
	// RequiresOneOf records a oneOf whose members are requirement-only
	// fragments (SecretWrite), which is not expressible as a union. Each inner
	// slice is one alternative's required property set.
	RequiresOneOf [][]string
}

// Property returns the named property of an object, or nil.
func (t *Type) Property(name string) *Type {
	if index := t.propertyIndex(name); index >= 0 {
		return t.Properties[index].Type
	}
	return nil
}

// propertyIndex returns the position of a named property, or -1.
func (t *Type) propertyIndex(name string) int {
	for i, p := range t.Properties {
		if p.Name == name {
			return i
		}
	}
	return -1
}

// IsRequired reports whether the named property is in the required set.
func (t *Type) IsRequired(name string) bool {
	for _, r := range t.Required {
		if r == name {
			return true
		}
	}
	return false
}

// Schema is one named component schema.
type Schema struct {
	Name string
	Type *Type
}

// Spec is the resolved components.schemas section, sorted by name.
type Spec struct {
	Schemas []*Schema

	byName map[string]*Schema
}

// Lookup returns the named schema, or nil.
func (s *Spec) Lookup(name string) *Schema {
	return s.byName[name]
}

// Keywords the generator understands structurally.
var handledKeywords = map[string]bool{
	"type": true, "properties": true, "required": true, "additionalProperties": true,
	"items": true, "enum": true, "format": true, "$ref": true,
	"allOf": true, "oneOf": true, "anyOf": true, "nullable": true, "description": true,
}

// Keywords that constrain values but do not change the emitted type. They are
// accepted and ignored: the models describe shapes, not validation.
var ignoredKeywords = map[string]bool{
	"minimum": true, "maximum": true, "exclusiveMinimum": true, "exclusiveMaximum": true,
	"minLength": true, "maxLength": true, "pattern": true, "minItems": true,
	"maxItems": true, "uniqueItems": true, "minProperties": true, "maxProperties": true,
	"default": true, "writeOnly": true, "readOnly": true, "title": true,
	"example": true, "examples": true, "deprecated": true,
}

// schemaPath is the JSON path of a component schema, used in error messages.
func schemaPath(name string) string {
	return "#/components/schemas/" + name
}

// yamlEntry is one key/value pair of a mapping node, in document order.
type yamlEntry struct {
	key   string
	value *yaml.Node
}

// parser resolves one document. It memoises named schemas so a schema shared by
// several refs is resolved once, and tracks in-progress names to catch cycles.
type parser struct {
	file     string
	nodes    map[string]*yaml.Node
	resolved map[string]*Type
	busy     map[string]bool
}

// Parse reads an OpenAPI document and resolves components.schemas. An allOf
// merged inside a property is given a synthesised component name, so every type
// the emitters see is either a scalar, a container or a named schema.
func Parse(src []byte, file string) (*Spec, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 {
		return nil, fmt.Errorf("%s: not an OpenAPI document", file)
	}
	root := doc.Content[0]
	if root.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("%s: not an OpenAPI document", file)
	}

	p := &parser{
		file:     file,
		nodes:    map[string]*yaml.Node{},
		resolved: map[string]*Type{},
		busy:     map[string]bool{},
	}

	schemas := lookupKey(lookupKey(root, "components"), "schemas")
	if schemas == nil || schemas.Kind != yaml.MappingNode {
		return nil, p.errf("#/components/schemas", "missing components.schemas object")
	}
	entries, err := p.entries(schemas, "#/components/schemas")
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(entries))
	for _, entry := range entries {
		if err := p.checkSchemaName(entry.key, "#/components/schemas/"+entry.key); err != nil {
			return nil, err
		}
		p.nodes[entry.key] = entry.value
		names = append(names, entry.key)
	}
	sort.Strings(names)

	spec := &Spec{Schemas: make([]*Schema, 0, len(names)), byName: map[string]*Schema{}}
	for _, name := range names {
		resolved, err := p.resolveName(name)
		if err != nil {
			return nil, err
		}
		schema := &Schema{Name: name, Type: resolved}
		spec.Schemas = append(spec.Schemas, schema)
	}
	// An allOf merged inside a property (Partial.error) has no component name of
	// its own; synthesise one now that every declared name is known, so both
	// emitters can declare the merged required set instead of collapsing to the
	// referenced type.
	taken := make(map[string]bool, len(names))
	for _, name := range names {
		taken[name] = true
	}
	synthesised := make([]*Schema, 0, 1)
	for _, schema := range spec.Schemas {
		if err := p.hoist(schema.Type, schema.Name, schemaPath(schema.Name), taken, &synthesised); err != nil {
			return nil, err
		}
	}
	spec.Schemas = append(spec.Schemas, synthesised...)
	sort.Slice(spec.Schemas, func(i, j int) bool { return spec.Schemas[i].Name < spec.Schemas[j].Name })
	for _, schema := range spec.Schemas {
		if err := p.checkInline(schema.Type, schemaPath(schema.Name), true); err != nil {
			return nil, err
		}
		spec.byName[schema.Name] = schema
	}
	return spec, nil
}

// errf renders a parse error with the file and JSON path the caller can jump to.
func (p *parser) errf(jsonPath, format string, args ...any) error {
	return fmt.Errorf("%s: %s: %s", p.file, jsonPath, fmt.Sprintf(format, args...))
}

// entries returns the ordered key/value pairs of a mapping node.
func (p *parser) entries(n *yaml.Node, path string) ([]yamlEntry, error) {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil, p.errf(path, "expected a mapping")
	}
	if len(n.Content)%2 != 0 {
		return nil, p.errf(path, "malformed mapping")
	}
	out := make([]yamlEntry, 0, len(n.Content)/2)
	for i := 0; i < len(n.Content); i += 2 {
		key, value := n.Content[i], n.Content[i+1]
		if key.Kind != yaml.ScalarNode {
			return nil, p.errf(path, "mapping key is not a scalar")
		}
		out = append(out, yamlEntry{key: key.Value, value: value})
	}
	return out, nil
}

// lookupKey returns the value of key in a mapping node, or nil. A nil node is
// tolerated so callers can chain lookups.
func lookupKey(n *yaml.Node, key string) *yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Kind == yaml.ScalarNode && n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

// resolveName resolves one named schema, memoising the result.
func (p *parser) resolveName(name string) (*Type, error) {
	if resolved, ok := p.resolved[name]; ok {
		return resolved, nil
	}
	node, ok := p.nodes[name]
	if !ok {
		return nil, p.errf(schemaPath(name), "schema is not declared in components.schemas")
	}
	if p.busy[name] {
		return nil, p.errf(schemaPath(name), "circular allOf reference")
	}
	p.busy[name] = true
	resolved, err := p.resolveNode(node, schemaPath(name))
	delete(p.busy, name)
	if err != nil {
		return nil, err
	}
	p.resolved[name] = resolved
	return resolved, nil
}

// resolveNode resolves one schema node into a Type.
func (p *parser) resolveNode(n *yaml.Node, path string) (*Type, error) {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil, p.errf(path, "schema must be a mapping")
	}
	if err := p.checkKeywords(n, path); err != nil {
		return nil, err
	}

	description := scalarText(lookupKey(n, "description"))
	nullable, err := p.booleanKeyword(n, "nullable", path)
	if err != nil {
		return nil, err
	}

	if ref := lookupKey(n, "$ref"); ref != nil {
		return p.resolveRef(n, ref, path, description, nullable)
	}
	if allOf := lookupKey(n, "allOf"); allOf != nil {
		if err := p.rejectCombinatorSiblings(n, "allOf", path); err != nil {
			return nil, err
		}
		merged, err := p.mergeAllOf(allOf, path+"/allOf")
		if err != nil {
			return nil, err
		}
		return decorate(merged, description, nullable), nil
	}
	if oneOf := lookupKey(n, "oneOf"); oneOf != nil {
		return p.combine(n, oneOf, "oneOf", path, description, nullable)
	}
	if anyOf := lookupKey(n, "anyOf"); anyOf != nil {
		return p.combine(n, anyOf, "anyOf", path, description, nullable)
	}
	return p.base(n, path, description, nullable)
}

// shapedKeywords are the keywords that describe a node's own shape. A node that
// carries one next to a combinator would have it silently ignored, so it is a
// hard error instead.
var shapedKeywords = map[string]bool{
	"properties": true, "required": true, "additionalProperties": true,
	"items": true, "type": true, "enum": true,
}

// combinatorKeywords are the union/merge keywords. Two on one node are
// ambiguous, and the parser would silently apply only the first.
var combinatorKeywords = map[string]bool{
	"allOf": true, "oneOf": true, "anyOf": true,
}

// rejectCombinatorSiblings fails loudly when a combinator would swallow a
// sibling that shapes the node: `allOf`/`oneOf`/`anyOf` members only describe
// their own schemas, the parent's properties are never merged in.
func (p *parser) rejectCombinatorSiblings(n *yaml.Node, keyword, path string) error {
	entries, err := p.entries(n, path)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.key == keyword {
			continue
		}
		if !shapedKeywords[entry.key] && !combinatorKeywords[entry.key] {
			continue
		}
		return p.errf(path, "%s cannot be combined with a sibling %q; "+
			"move it into one of the %s members", keyword, entry.key, keyword)
	}
	return nil
}

// checkKeywords rejects a schema keyword the generator would otherwise ignore.
func (p *parser) checkKeywords(n *yaml.Node, path string) error {
	entries, err := p.entries(n, path)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if handledKeywords[entry.key] || ignoredKeywords[entry.key] {
			continue
		}
		return p.errf(path, "unsupported schema keyword %q", entry.key)
	}
	return nil
}

// scalarText returns the text of a scalar node, or "" for nil/non-scalars.
func scalarText(n *yaml.Node) string {
	if n == nil || n.Kind != yaml.ScalarNode {
		return ""
	}
	return strings.TrimSpace(n.Value)
}

// booleanKeyword reads an optional boolean schema keyword.
func (p *parser) booleanKeyword(n *yaml.Node, key, path string) (bool, error) {
	node := lookupKey(n, key)
	if node == nil {
		return false, nil
	}
	if node.Kind != yaml.ScalarNode || node.Tag != "!!bool" {
		return false, p.errf(path, "%s must be true or false", key)
	}
	return node.Value == "true", nil
}

// resolveRef resolves a $ref node, keeping the reference symbolic.
func (p *parser) resolveRef(n *yaml.Node, ref *yaml.Node, path, description string, nullable bool) (*Type, error) {
	name, err := p.refName(ref, path)
	if err != nil {
		return nil, err
	}
	entries, err := p.entries(n, path)
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		switch entry.key {
		case "$ref", "description", "nullable":
		default:
			return nil, p.errf(path, "unsupported keyword %q next to $ref", entry.key)
		}
	}
	if _, ok := p.nodes[name]; !ok {
		return nil, p.errf(path, "$ref names undeclared schema %q", name)
	}
	return &Type{Kind: KindRef, Ref: name, Description: description, Nullable: nullable}, nil
}

// refName extracts the component name from "#/components/schemas/Name".
func (p *parser) refName(ref *yaml.Node, path string) (string, error) {
	const prefix = "#/components/schemas/"
	raw := scalarText(ref)
	if !strings.HasPrefix(raw, prefix) {
		return "", p.errf(path, "unsupported $ref %q; want %s<Name>", raw, prefix)
	}
	name := strings.TrimPrefix(raw, prefix)
	if name == "" || strings.Contains(name, "/") {
		return "", p.errf(path, "unsupported $ref %q; want %s<Name>", raw, prefix)
	}
	return name, nil
}

// base resolves a schema that is not a $ref or a combinator.
func (p *parser) base(n *yaml.Node, path, description string, nullable bool) (*Type, error) {
	kinds, listNullable, err := p.typeKinds(n, path)
	if err != nil {
		return nil, err
	}
	nullable = nullable || listNullable

	resolved := &Type{Description: description, Nullable: nullable}
	switch {
	case len(kinds) == 0:
		return nil, p.errf(path, "schema has no type")
	case len(kinds) == 1:
	default:
		return nil, p.errf(path, `type list must name exactly one type besides "null"`)
	}

	switch kinds[0] {
	case "object":
		resolved.Kind = KindObject
		if err := p.fillObject(n, path, resolved); err != nil {
			return nil, err
		}
	case "array":
		resolved.Kind = KindArray
		items := lookupKey(n, "items")
		if items == nil {
			return nil, p.errf(path, "array schema has no items")
		}
		resolved.Items, err = p.resolveNode(items, path+"/items")
		if err != nil {
			return nil, err
		}
	case "string":
		resolved.Kind = KindString
		resolved.Format = scalarText(lookupKey(n, "format"))
	case "integer":
		resolved.Kind = KindInteger
		resolved.Format = scalarText(lookupKey(n, "format"))
	case "number":
		resolved.Kind = KindNumber
		resolved.Format = scalarText(lookupKey(n, "format"))
	case "boolean":
		resolved.Kind = KindBoolean
	case "null":
		resolved.Kind = KindNull
	default:
		return nil, p.errf(path, "unsupported type %q", kinds[0])
	}

	if enum := lookupKey(n, "enum"); enum != nil {
		return p.applyEnum(enum, path, resolved)
	}
	return resolved, nil
}

// typeKinds reads the type keyword, which is a string or (in 3.1) a list that
// may include "null". A node without type infers object from properties and
// array from items, which JSON Schema allows.
func (p *parser) typeKinds(n *yaml.Node, path string) ([]string, bool, error) {
	node := lookupKey(n, "type")
	if node == nil {
		switch {
		case lookupKey(n, "properties") != nil || lookupKey(n, "additionalProperties") != nil:
			return []string{"object"}, false, nil
		case lookupKey(n, "items") != nil:
			return []string{"array"}, false, nil
		default:
			return nil, false, p.errf(path, "schema has no type")
		}
	}
	switch node.Kind {
	case yaml.ScalarNode:
		return []string{node.Value}, false, nil
	case yaml.SequenceNode:
		kinds := make([]string, 0, len(node.Content))
		nullable := false
		for _, item := range node.Content {
			if item.Kind != yaml.ScalarNode {
				return nil, false, p.errf(path, "type list must contain only strings")
			}
			if item.Value == "null" {
				nullable = true
				continue
			}
			kinds = append(kinds, item.Value)
		}
		if nullable && len(kinds) == 0 {
			return []string{"null"}, false, nil
		}
		return kinds, nullable, nil
	default:
		return nil, false, p.errf(path, "type must be a string or a list of strings")
	}
}

// fillObject reads properties, required and additionalProperties.
func (p *parser) fillObject(n *yaml.Node, path string, resolved *Type) error {
	properties := lookupKey(n, "properties")
	if properties != nil {
		entries, err := p.entries(properties, path+"/properties")
		if err != nil {
			return err
		}
		for _, entry := range entries {
			propertyPath := path + "/properties/" + entry.key
			if err := p.checkPropertyName(entry.key, propertyPath); err != nil {
				return err
			}
			propType, err := p.resolveNode(entry.value, propertyPath)
			if err != nil {
				return err
			}
			resolved.Properties = append(resolved.Properties, Property{Name: entry.key, Type: propType})
		}
	}

	required := lookupKey(n, "required")
	if required != nil {
		names, err := p.stringList(required, path+"/required")
		if err != nil {
			return err
		}
		resolved.Required = names
		if properties != nil {
			for _, name := range names {
				if resolved.Property(name) == nil {
					return p.errf(path, "required names undeclared property %q", name)
				}
			}
		}
	}

	extra := lookupKey(n, "additionalProperties")
	if extra == nil {
		return nil
	}
	switch extra.Kind {
	case yaml.ScalarNode:
		if extra.Tag != "!!bool" {
			return p.errf(path, "additionalProperties must be true, false or a schema")
		}
		resolved.HasExtra = extra.Value == "true"
	case yaml.MappingNode:
		resolved.HasExtra = true
		value, err := p.resolveNode(extra, path+"/additionalProperties")
		if err != nil {
			return err
		}
		resolved.Extra = value
	default:
		return p.errf(path, "additionalProperties must be true, false or a schema")
	}
	return nil
}

// stringList reads a sequence of scalars, preserving order.
func (p *parser) stringList(n *yaml.Node, path string) ([]string, error) {
	if n == nil || n.Kind != yaml.SequenceNode {
		return nil, p.errf(path, "expected a list of strings")
	}
	out := make([]string, 0, len(n.Content))
	seen := map[string]bool{}
	for _, item := range n.Content {
		if item.Kind != yaml.ScalarNode {
			return nil, p.errf(path, "expected a list of strings")
		}
		if seen[item.Value] {
			continue
		}
		seen[item.Value] = true
		out = append(out, item.Value)
	}
	return out, nil
}

// applyEnum turns a scalar schema into an enum schema.
func (p *parser) applyEnum(enum *yaml.Node, path string, resolved *Type) (*Type, error) {
	switch resolved.Kind {
	case KindString, KindInteger, KindNumber, KindBoolean:
	default:
		return nil, p.errf(path, "enum is only supported on a scalar schema")
	}
	if enum.Kind != yaml.SequenceNode || len(enum.Content) == 0 {
		return nil, p.errf(path, "enum must be a non-empty list of scalars")
	}
	literals := make([]Literal, 0, len(enum.Content))
	for _, item := range enum.Content {
		if item.Kind != yaml.ScalarNode || item.Tag == "!!null" {
			return nil, p.errf(path, "enum values must be non-null scalars")
		}
		literals = append(literals, Literal{
			Raw:      item.Value,
			IsString: item.Tag == "!!str",
			IsBool:   item.Tag == "!!bool",
		})
	}
	resolved.Kind = KindEnum
	resolved.Enum = literals
	return resolved, nil
}

// mergeAllOf merges every member into one object.
func (p *parser) mergeAllOf(list *yaml.Node, path string) (*Type, error) {
	if list.Kind != yaml.SequenceNode || len(list.Content) == 0 {
		return nil, p.errf(path, "allOf must be a non-empty list")
	}
	merged := &Type{Kind: KindObject, Merged: true}
	for i, member := range list.Content {
		memberPath := fmt.Sprintf("%s/%d", path, i)
		memberType, err := p.member(member, memberPath)
		if err != nil {
			return nil, err
		}
		if memberType.Kind != KindObject {
			return nil, p.errf(memberPath, "allOf member must be an object schema after $ref resolution")
		}
		if err := p.mergeInto(merged, memberType, path); err != nil {
			return nil, err
		}
	}
	// A required name no member declares is a spec bug, not a modelling choice:
	// the merged object would claim a property it never describes.
	for _, name := range merged.Required {
		if merged.Property(name) == nil {
			return nil, p.errf(path, "required names undeclared property %q", name)
		}
	}
	return merged, nil
}

// member resolves an allOf/oneOf/anyOf member, expanding a $ref member to the
// schema it names so the parent can merge it.
func (p *parser) member(n *yaml.Node, path string) (*Type, error) {
	if ref := lookupKey(n, "$ref"); ref != nil {
		name, err := p.refName(ref, path)
		if err != nil {
			return nil, err
		}
		for i := 0; i+1 < len(n.Content); i += 2 {
			key := n.Content[i].Value
			if key != "$ref" && key != "description" {
				return nil, p.errf(path, "unsupported keyword %q next to $ref", key)
			}
		}
		return p.resolveName(name)
	}
	return p.resolveNode(n, path)
}

// mergeInto folds one object into the accumulator. Later members win on a name
// clash, unless the two declarations disagree about the type.
func (p *parser) mergeInto(merged, member *Type, path string) error {
	for _, prop := range member.Properties {
		if index := merged.propertyIndex(prop.Name); index >= 0 {
			if !sameType(merged.Properties[index].Type, prop.Type) {
				return p.errf(path, "conflicting types for property %q", prop.Name)
			}
			// Later members win on a name clash: their declaration (and with it
			// their description) replaces the earlier one.
			merged.Properties[index].Type = prop.Type
			if !merged.IsRequired(prop.Name) && member.IsRequired(prop.Name) {
				merged.Required = append(merged.Required, prop.Name)
			}
			continue
		}
		merged.Properties = append(merged.Properties, prop)
		if member.IsRequired(prop.Name) {
			merged.Required = append(merged.Required, prop.Name)
		}
	}
	for _, name := range member.Required {
		if !merged.IsRequired(name) {
			merged.Required = append(merged.Required, name)
		}
	}
	if member.HasExtra {
		merged.HasExtra = true
		merged.Extra = member.Extra
	}
	return nil
}

// combine resolves oneOf/anyOf.
func (p *parser) combine(n, list *yaml.Node, keyword, path, description string, nullable bool) (*Type, error) {
	memberPath := path + "/" + keyword
	if list.Kind != yaml.SequenceNode || len(list.Content) == 0 {
		return nil, p.errf(memberPath, "%s must be a non-empty list", keyword)
	}

	fragments := 0
	for _, member := range list.Content {
		if isRequirementFragment(member) {
			fragments++
		}
	}
	if fragments > 0 {
		return p.combineRequirements(n, list, keyword, path, description, nullable, fragments)
	}
	// A requirement-only oneOf legitimately sits next to the parent object's
	// properties; every other sibling would be dropped by the union.
	if err := p.rejectCombinatorSiblings(n, keyword, path); err != nil {
		return nil, err
	}

	variants := make([]*Type, 0, len(list.Content))
	for i, member := range list.Content {
		variant, err := p.resolveNode(member, fmt.Sprintf("%s/%d", memberPath, i))
		if err != nil {
			return nil, err
		}
		if variant.Kind == KindNull {
			nullable = true
			continue
		}
		variants = append(variants, variant)
	}
	switch len(variants) {
	case 0:
		return &Type{Kind: KindNull, Description: description}, nil
	case 1:
		only := *variants[0]
		only.Nullable = only.Nullable || nullable
		if description != "" {
			only.Description = description
		}
		return &only, nil
	default:
		return &Type{Kind: KindUnion, Variants: variants, Nullable: nullable, Description: description}, nil
	}
}

// combineRequirements records a oneOf whose members only name required sets.
// Such a constraint cannot be a union, so it is attached to the parent object.
func (p *parser) combineRequirements(n, list *yaml.Node, keyword, path, description string,
	nullable bool, fragments int) (*Type, error) {
	memberPath := path + "/" + keyword
	if keyword != "oneOf" {
		return nil, p.errf(memberPath, "requirement-only %s members are not supported", keyword)
	}
	if fragments != len(list.Content) {
		return nil, p.errf(memberPath, "cannot mix requirement-only and typed oneOf members")
	}
	if lookupKey(n, "type") == nil && lookupKey(n, "properties") == nil && lookupKey(n, "additionalProperties") == nil {
		return nil, p.errf(memberPath, "oneOf requirement fragments need a parent object schema")
	}

	resolved, err := p.base(n, path, description, nullable)
	if err != nil {
		return nil, err
	}
	for i, member := range list.Content {
		required, err := p.stringList(lookupKey(member, "required"),
			fmt.Sprintf("%s/%d/required", memberPath, i))
		if err != nil {
			return nil, err
		}
		if len(required) == 0 {
			return nil, p.errf(fmt.Sprintf("%s/%d", memberPath, i), "oneOf member names no required property")
		}
		resolved.RequiresOneOf = append(resolved.RequiresOneOf, required)
	}
	return resolved, nil
}

// isRequirementFragment reports whether a member only constrains requirements
// (SecretWrite's `- required: [data]`) instead of describing a shape.
func isRequirementFragment(n *yaml.Node) bool {
	if n == nil || n.Kind != yaml.MappingNode {
		return false
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		switch n.Content[i].Value {
		case "required", "description":
		default:
			return false
		}
	}
	return lookupKey(n, "required") != nil
}

// decorate applies a node's own description and nullable flag.
func decorate(resolved *Type, description string, nullable bool) *Type {
	if description != "" {
		resolved.Description = description
	}
	resolved.Nullable = resolved.Nullable || nullable
	return resolved
}

// hoist gives every inline allOf-merged object a component name and rewrites its
// slot to a $ref, so a merged required set survives into both languages. Other
// inline objects stay rejected by checkInline: they need no name.
func (p *parser) hoist(t *Type, owner, path string, taken map[string]bool, out *[]*Schema) error {
	if t == nil {
		return nil
	}
	for i := range t.Properties {
		property := &t.Properties[i]
		replacement, err := p.hoistSlot(
			property.Type, owner+exportedName(property.Name), path+"/properties/"+property.Name, taken, out)
		if err != nil {
			return err
		}
		property.Type = replacement
	}
	if t.Items != nil {
		replacement, err := p.hoistSlot(t.Items, owner+"Item", path+"/items", taken, out)
		if err != nil {
			return err
		}
		t.Items = replacement
	}
	for i := range t.Variants {
		replacement, err := p.hoistSlot(
			t.Variants[i], fmt.Sprintf("%sVariant%d", owner, i+1),
			fmt.Sprintf("%s/variants/%d", path, i), taken, out)
		if err != nil {
			return err
		}
		t.Variants[i] = replacement
	}
	if t.Extra != nil {
		replacement, err := p.hoistSlot(t.Extra, owner+"Value", path+"/additionalProperties", taken, out)
		if err != nil {
			return err
		}
		t.Extra = replacement
	}
	return nil
}

// hoistSlot returns the type that should replace a child slot: the original, or
// a $ref to a synthesised schema when the slot holds an inline merged object.
func (p *parser) hoistSlot(t *Type, name, path string, taken map[string]bool, out *[]*Schema) (*Type, error) {
	if t == nil {
		return nil, nil
	}
	if t.Kind != KindObject || !t.Merged || len(t.Properties) == 0 {
		if err := p.hoist(t, name, path, taken, out); err != nil {
			return nil, err
		}
		return t, nil
	}
	if taken[name] {
		return nil, p.errf(path, "cannot synthesise a type named %q: the name is already taken", name)
	}
	if err := p.hoist(t, name, path, taken, out); err != nil {
		return nil, err
	}
	hoisted := *t
	// Nullability belongs to the slot, not to the synthesised object.
	hoisted.Nullable = false
	taken[name] = true
	*out = append(*out, &Schema{Name: name, Type: &hoisted})
	return &Type{Kind: KindRef, Ref: name, Nullable: t.Nullable}, nil
}

// exportedName upper-cases the first rune of a property name so it can prefix a
// synthesised component name: Partial + error = PartialError.
func exportedName(name string) string {
	if name == "" {
		return ""
	}
	runes := []rune(name)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

// checkInline rejects an inline object with named properties: only a named
// component schema can become a class or an interface.
func (p *parser) checkInline(t *Type, path string, root bool) error {
	if t == nil || t.Kind == KindRef {
		return nil
	}
	if !root && t.Kind == KindObject && len(t.Properties) > 0 {
		return p.errf(path, "inline object with named properties is not supported; "+
			"declare a component schema and use $ref")
	}
	for _, prop := range t.Properties {
		if err := p.checkInline(prop.Type, path+"/properties/"+prop.Name, false); err != nil {
			return err
		}
	}
	if err := p.checkInline(t.Items, path+"/items", false); err != nil {
		return err
	}
	for i, variant := range t.Variants {
		if err := p.checkInline(variant, fmt.Sprintf("%s/variants/%d", path, i), false); err != nil {
			return err
		}
	}
	return p.checkInline(t.Extra, path+"/additionalProperties", false)
}

// sameType reports whether two declarations describe the same shape. It is used
// to reject an allOf that states two types for one property.
func sameType(a, b *Type) bool {
	if a == nil || b == nil {
		return a == nil && b == nil
	}
	if a.Kind != b.Kind || a.Nullable != b.Nullable || a.Ref != b.Ref ||
		a.Format != b.Format || a.HasExtra != b.HasExtra {
		return false
	}
	return sameEnum(a.Enum, b.Enum) &&
		sameType(a.Items, b.Items) &&
		sameType(a.Extra, b.Extra) &&
		sameVariants(a.Variants, b.Variants) &&
		sameProperties(a.Properties, b.Properties) &&
		strings.Join(a.Required, ",") == strings.Join(b.Required, ",")
}

// sameEnum reports whether two literal lists are identical.
func sameEnum(a, b []Literal) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// sameVariants reports whether two union member lists are identical.
func sameVariants(a, b []*Type) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if !sameType(a[i], b[i]) {
			return false
		}
	}
	return true
}

// sameProperties reports whether two property lists are identical.
func sameProperties(a, b []Property) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i].Name != b[i].Name || !sameType(a[i].Type, b[i].Type) {
			return false
		}
	}
	return true
}
